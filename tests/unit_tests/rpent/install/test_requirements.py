"""Requirements rendering is stable and hashes cover every install input."""

import pytest

from rpent.install.errors import InstallConfigError
from rpent.install.fingerprint import FINGERPRINT_SCHEMA_FIELD
from rpent.install.requirements import (
    FINGERPRINT_SCHEMA,
    read_core_dependencies,
    read_planner_dependencies,
    read_uv_settings,
    render_requirements,
    requirements_inputs,
    requirements_sha256,
)
from rpent.install.resolve import resolve


@pytest.fixture
def resolution(make_component, make_catalog):
    robot = make_component(
        "robot-alpha",
        dependencies=["torch==2.7.0", "numpy>=2"],
        requires=["model-sam3"],
    )
    sam3 = make_component("model-sam3", dependencies=["transformers>=4.57"])
    catalog = make_catalog(components=[robot, sam3])
    return resolve(["robot-alpha"], catalog)


def test_render_requirements_names_the_targets_and_groups_the_components(resolution):
    text = render_requirements(
        resolution,
        core_dependencies=("PyYAML", "packaging"),
    )

    assert text.splitlines()[:3] == [
        "# Generated by rpent-install for: robot-alpha.",
        "# Do not edit; change a component manifest and rerun",
        "# `rpent-install install robot-alpha`.",
    ]
    assert "# RPent core\nPyYAML\npackaging" in text
    assert "# component model-sam3\ntransformers>=4.57" in text
    assert "# component robot-alpha\nnumpy>=2\ntorch==2.7.0" in text
    # Sorted components put the closure member first.
    assert text.index("# component model-sam3") < text.index("# component robot-alpha")


def test_render_requirements_adds_the_planner_layer_for_planner_components(
    make_component, make_catalog
):
    runtime = make_component("sim-alpha")
    planner = make_component("robot-alpha", planner=True)
    catalog = make_catalog(components=[runtime, planner])
    layer = ("pydantic>=2", "scipy")

    runtime_text = render_requirements(
        resolve(["sim-alpha"], catalog),
        core_dependencies=("numpy",),
        planner_dependencies=layer,
    )
    planner_text = render_requirements(
        resolve(["robot-alpha"], catalog),
        core_dependencies=("numpy",),
        planner_dependencies=layer,
    )

    # A simulator environment keeps the runtime layer alone.
    assert "# RPent planner" not in runtime_text
    assert "# RPent planner (rpent[planner])\npydantic>=2\nscipy" in planner_text
    assert planner_text.index("# RPent core") < planner_text.index("# RPent planner")
    # The runtime layer is not repeated in the planner block.
    assert planner_text.count("numpy") == 1


def test_render_requirements_omits_components_without_dependencies(
    make_component, make_catalog
):
    catalog = make_catalog(components=[make_component("robot-alpha")])

    text = render_requirements(resolve(["robot-alpha"], catalog))

    assert "# RPent core" not in text
    assert "# component" not in text


def test_requirements_inputs_record_the_closure(resolution, tmp_path):
    inputs = requirements_inputs(
        resolution, root=tmp_path, core_dependencies=("packaging",)
    )

    assert inputs[FINGERPRINT_SCHEMA_FIELD] == FINGERPRINT_SCHEMA
    # Targets name the directory and the record; only the closure decides what
    # the environment contains.
    assert "targets" not in inputs
    assert sorted(inputs["components"]) == ["model-sam3", "robot-alpha"]
    assert inputs["core_dependencies"] == ["packaging"]
    assert inputs["planner_dependencies"] == []
    assert inputs["index"] == {"url": None, "extra_urls": [], "strategy": None}
    assert inputs["overrides"] == []


def test_requirements_inputs_record_the_planner_layer_only_when_installed(
    make_component, make_catalog, tmp_path
):
    runtime = make_component("sim-alpha")
    planner = make_component("robot-alpha", planner=True)
    catalog = make_catalog(components=[runtime, planner])

    runtime_inputs = requirements_inputs(
        resolve(["sim-alpha"], catalog),
        root=tmp_path,
        planner_dependencies=("pydantic>=2",),
    )
    planner_inputs = requirements_inputs(
        resolve(["robot-alpha"], catalog),
        root=tmp_path,
        planner_dependencies=("pydantic>=2",),
    )

    assert runtime_inputs["planner_dependencies"] == []
    assert planner_inputs["planner_dependencies"] == ["pydantic>=2"]


def test_requirements_hash_ignores_how_the_closure_was_named(
    make_component, make_catalog, tmp_path
):
    base = make_component("infra-base")
    top = make_component("robot-alpha", requires=("infra-base",))
    catalog = make_catalog(components=[base, top])

    # Naming the required component as well describes the same environment, so
    # it must not make the recorded inputs look stale.
    assert requirements_sha256(
        resolve(["robot-alpha"], catalog), root=tmp_path
    ) == requirements_sha256(
        resolve(["robot-alpha", "infra-base"], catalog), root=tmp_path
    )


def test_requirements_hash_tracks_manifests_and_core_dependencies(resolution, tmp_path):
    baseline = requirements_sha256(
        resolution, root=tmp_path, core_dependencies=("packaging",)
    )

    assert baseline == requirements_sha256(
        resolution, root=tmp_path, core_dependencies=("packaging",)
    )
    assert baseline != requirements_sha256(
        resolution, root=tmp_path, core_dependencies=("packaging", "pytest")
    )


def test_requirements_hash_tracks_index_settings(
    make_component, make_catalog, tmp_path
):
    default = make_component("infra-unit_cpu")
    raised = make_component(
        "infra-unit_cpu",
        index_url="https://download.pytorch.org/whl/cpu",
        extra_index_urls=("https://pypi.org/simple",),
        index_strategy="unsafe-first-match",
    )
    default_resolution = resolve(["infra-unit_cpu"], make_catalog([default]))
    raised_resolution = resolve(["infra-unit_cpu"], make_catalog([raised]))

    # Index settings decide which wheels uv may select, so they are inputs even
    # though they do not appear in the rendered requirements.
    assert requirements_sha256(
        default_resolution, root=tmp_path
    ) != requirements_sha256(raised_resolution, root=tmp_path)
    assert requirements_inputs(raised_resolution, root=tmp_path)["index"] == {
        "url": "https://download.pytorch.org/whl/cpu",
        "extra_urls": ["https://pypi.org/simple"],
        "strategy": "unsafe-first-match",
    }


def test_requirements_hash_tracks_component_overrides(
    make_component, make_catalog, tmp_path, write_toml
):
    declared = "robots/alpha/requirements/override.txt"
    # Manifests resolve overrides to absolute paths when they are loaded.
    override = write_toml(declared, "numpy<2")
    robot = make_component(
        "robot-alpha", dependencies=["numpy>=2"], overrides=[override]
    )
    resolution = resolve(["robot-alpha"], make_catalog([robot]))

    baseline = requirements_sha256(resolution, root=tmp_path)
    inputs = requirements_inputs(resolution, root=tmp_path)
    assert [entry["path"] for entry in inputs["overrides"]] == [str(declared)]

    override.write_text("numpy<3\n", encoding="utf-8")
    changed = requirements_sha256(resolution, root=tmp_path)
    assert baseline != changed

    # Files the installation never reads are not inputs.
    write_toml("robots/alpha/README.md", "notes")
    assert changed == requirements_sha256(resolution, root=tmp_path)


def test_requirement_file_hashes_ignore_comments_and_blank_lines(
    make_component, make_catalog, tmp_path, write_toml
):
    override = write_toml("robots/alpha/requirements/override.txt", "numpy<2")
    robot = make_component(
        "robot-alpha", dependencies=["numpy>=2"], overrides=[override]
    )
    resolution = resolve(["robot-alpha"], make_catalog([robot]))

    baseline = requirements_sha256(resolution, root=tmp_path)

    # uv ignores comments and blank lines, so editing them cannot change what
    # a reinstall produces.
    override.write_text("# pinned for the simulator stack\n\nnumpy<2\n")
    assert baseline == requirements_sha256(resolution, root=tmp_path)

    override.write_text("numpy<3\n")
    assert baseline != requirements_sha256(resolution, root=tmp_path)


def test_requirement_file_that_is_not_utf8_is_a_configuration_error(
    make_component, make_catalog, tmp_path
):
    override = tmp_path / "robots/alpha/requirements/override.txt"
    override.parent.mkdir(parents=True)
    override.write_text("numpy<2\n", encoding="utf-8")
    robot = make_component("robot-alpha", overrides=[override])
    resolution = resolve(["robot-alpha"], make_catalog([robot]))

    # uv rejects a requirement file it cannot decode, so recording it as an
    # absent input would hide the problem behind a drift report.
    override.write_bytes(b"numpy\n\xff\n")

    with pytest.raises(InstallConfigError, match="not UTF-8"):
        requirements_inputs(resolution, root=tmp_path)


def test_requirements_hash_does_not_depend_on_how_the_checkout_is_named(
    make_component, make_catalog, tmp_path
):
    checkout = tmp_path / "checkout"
    override = checkout / "robots/alpha/requirements/override.txt"
    override.parent.mkdir(parents=True)
    override.write_text("numpy<2\n", encoding="utf-8")
    robot = make_component("robot-alpha", overrides=[override])
    resolution = resolve(["robot-alpha"], make_catalog([robot]))

    linked = tmp_path / "linked"
    linked.symlink_to(checkout, target_is_directory=True)

    assert requirements_sha256(resolution, root=linked) == requirements_sha256(
        resolution, root=checkout
    )


def test_requirements_hash_tracks_uv_settings(
    make_component, make_catalog, tmp_path, write_toml
):
    resolution = resolve(["robot-alpha"], make_catalog([make_component("robot-alpha")]))
    settings = """
        [project]
        name = "rpent"
        dependencies = []

        [tool.uv]
        prerelease = "allow"
        extra-build-dependencies = {}
    """
    pyproject = write_toml("pyproject.toml", settings)

    baseline = requirements_sha256(resolution, root=tmp_path)
    assert requirements_inputs(resolution, root=tmp_path)["uv_settings"] == {
        "prerelease": "allow",
        "extra-build-dependencies": {},
    }

    pyproject.write_text(
        settings.replace('prerelease = "allow"', 'prerelease = "disallow"').strip()
        + "\n",
        encoding="utf-8",
    )
    assert baseline != requirements_sha256(resolution, root=tmp_path)


