@pytest.mark.parametrize(
    "text",
    [
        "",
        "[project]\nname = 'alpha'\n",
        "[project]\ndependencies = 'packaging'\n",
    ],
)
def test_read_core_dependencies_rejects_missing_table(write_toml, tmp_path, text):
    write_toml("pyproject.toml", text)

    with pytest.raises(InstallConfigError):
        read_core_dependencies(tmp_path)


@pytest.mark.parametrize(
    ("reader", "message"),
    [
        (read_core_dependencies, "cannot read core dependencies"),
        (read_uv_settings, "cannot read \\[tool.uv\\]"),
    ],
)
def test_a_pyproject_that_is_not_utf8_is_a_configuration_error(
    tmp_path, reader, message
):
    # ``tomllib`` decodes the bytes before parsing, so a bad encoding raises
    # ``UnicodeDecodeError``; letting it escape ends ``rpent-install`` in a
    # traceback instead of reporting the checkout it cannot read.
    (tmp_path / "pyproject.toml").write_bytes(b"[project]\nname = 'alpha'\n# \xff\n")

    with pytest.raises(InstallConfigError, match=message):
        reader(tmp_path)
