"""Offline checks for the module commands generated by ROS launch."""

import subprocess
import sys
from types import ModuleType
from unittest.mock import Mock

import pytest
import yaml

from robots.lekiwi.navigation import launch
from robots.lekiwi.runtime_config import set_robot_config_path


@pytest.mark.parametrize("hardware", [False, True])
@pytest.mark.parametrize("host", ["127.0.0.1", "server.example"])
def test_launch_starts_worker_modules_with_site_config(
    monkeypatch, tmp_path, hardware, host
):
    commands = []
    service = Mock()
    service.run.return_value = 0
    modules = {
        "ament_index_python.packages": {
            "get_package_share_directory": lambda name: str(tmp_path)
        },
        "launch": {"LaunchDescription": list, "LaunchService": lambda: service},
        "launch.actions": {
            "EmitEvent": Mock(),
            "ExecuteProcess": lambda **kw: commands.append(kw["cmd"]),
            "RegisterEventHandler": Mock(),
        },
        "launch.event_handlers": {"OnProcessExit": Mock()},
        "launch.events": {"Shutdown": Mock()},
        "launch_ros.actions": {"Node": Mock()},
    }
    for name, members in modules.items():
        module = ModuleType(name)
        module.__dict__.update(members)
        monkeypatch.setitem(sys.modules, name, module)
    site = tmp_path / "robot.yaml"
    localization = {"endpoint": f"http://{host}:18125"}
    site.write_text(yaml.safe_dump({"localization": localization}))
    set_robot_config_path(site)
    try:
        assert (
            launch.run_navigation(
                "http://127.0.0.1:8120", hardware, tmp_path / "map.yaml", "{}", 8121
            )
            == 0
        )
    finally:
        set_robot_config_path(None)
    assert len(commands) == 6
    modules = {
        "robots.lekiwi.navigation.bridge",
        "robots.lekiwi.navigation.perception",
        "robots.lekiwi.navigation.localization",
        "robots.lekiwi.navigation.nav2",
    }
    assert {cmd[2] for cmd in commands} == modules
    base = next(cmd for cmd in commands if "base" in cmd)
    assert ("--require-mock" in base) is (not hardware)
    for cmd in commands:
        assert cmd[cmd.index("--robot-config") + 1] == str(site)
        # Help must work in a fresh process without ROS or a valid site config.
        result = subprocess.run(
            [*cmd, "--help"], capture_output=True, text=True, timeout=20
        )
        assert result.returncode == 0, result.stderr
        assert "--robot-config" in result.stdout


def test_launch_cli_applies_site_config_before_building_parameters(
    monkeypatch, tmp_path
):
    from robots.lekiwi.navigation import config
    from robots.lekiwi.runtime_config import get_robot_config_path

    site = tmp_path / "robot.yaml"

    def parameters(map_yaml):
        assert get_robot_config_path() == site
        assert map_yaml == tmp_path / "map.yaml"
        return {}

    monkeypatch.setattr(config, "parameters", parameters)
    run = Mock(return_value=0)
    monkeypatch.setattr(launch, "run_navigation", run)
    try:
        with pytest.raises(SystemExit) as result:
            launch.main(
                [
                    "--robot-config",
                    str(site),
                    "--endpoint",
                    "http://127.0.0.1:8120",
                    "--map",
                    str(tmp_path / "map.yaml"),
                    "--rpc-port",
                    "8121",
                    "--hardware",
                ]
            )
        assert result.value.code == 0
        assert run.call_args.args[1] is True
    finally:
        set_robot_config_path(None)


@pytest.mark.parametrize(
    "module, entrypoint, worker, arguments",
    [
        ("perception", "main", "run_stereo", []),
        ("nav2", "main", "serve", ["--port", "8121"]),
        ("localization", "main", "stream_localization", ["stream"]),
        ("localization", "main", "publish_transform", ["transform"]),
        (
            "bridge",
            "bridge",
            "publish_camera",
            ["camera", "--endpoint", "http://127.0.0.1:8120"],
        ),
    ],
)
def test_worker_entrypoint_applies_site_config(
    monkeypatch, tmp_path, module, entrypoint, worker, arguments
):
    import importlib

    from robots.lekiwi.runtime_config import get_robot_config_path

    site = tmp_path / "robot.yaml"
    site.write_text("localization:\n  endpoint: http://cloud.invalid\n")
    module = importlib.import_module(f"robots.lekiwi.navigation.{module}")

    def run(*args, **kwargs):
        assert get_robot_config_path() == site

    started = Mock(side_effect=run)
    monkeypatch.setattr(module, worker, started)
    try:
        getattr(module, entrypoint)(["--robot-config", str(site), *arguments])
        started.assert_called_once()
    finally:
        set_robot_config_path(None)
